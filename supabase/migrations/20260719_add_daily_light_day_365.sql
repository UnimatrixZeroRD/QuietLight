The road of faith is not travelled by those who never wander.

It is travelled by those who continue returning to the Shepherd.

Do not confuse returning with failure.

Returning is one of the deepest practices of faith.

Every repentance is a return.

Every prayer after silence is a return.

Every act of forgiveness after bitterness is a return.

Every renewed step after collapse is a return.

Every morning in which we again say, “Lord, lead me,” is a return.

And the Lord is not wearied by sincere returning.

He is not standing at the door counting how many times we have come back.

He is the Father who sees the prodigal while he is still a great way off.

He runs.

He receives.

