God often works through the steady flame that continues burning through the night.

A dramatic fire may be seen from far away.

But a lantern carried beside a wounded traveller may bring someone home.

Do not underestimate quiet faithfulness.

Do not believe that your life matters only when it becomes large.

Do not assume that the kingdom advances only through public platforms, great institutions, famous leaders, or visible success.

The kingdom grows like seed.

Like leaven.

Like a mustard tree beginning from something small.

It advances through ordinary believers who love God, love their neighbours, speak truth, practise mercy, keep their promises, raise their children, care for the suffering, welcome the stranger, and continue praying when no one is watching.

